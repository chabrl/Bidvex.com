def get_translation(key: str, lang: str = "en", *format_args) -> str:
    """
    Get translation for a key in the specified language
    
    Args:
        key: Translation key
        lang: Language code ('en' or 'fr')
        *format_args: Arguments to format into the translation string
    
    Returns:
        Translated string with formatting applied
    """
    translation = TRANSLATIONS.get(key, {}).get(lang, TRANSLATIONS.get(key, {}).get("en", key))
    
    if format_args:
        return translation.format(*format_args)
    
    return translation
